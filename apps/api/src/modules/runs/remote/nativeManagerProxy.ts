import { CompactionStateSchema, ContextSnapshotSchema, SessionControlCapabilitiesSchema, SessionPreferencesSchema, type ContextSnapshot, type SessionPreferences } from '@graphql/contracts'
import type { NativeCompactInput } from '../../harnesses/port.js'
import { isDeepStrictEqual } from 'node:util'
import { setTimeout as delay } from 'node:timers/promises'
import { z } from 'zod'
import { NativeSessionReferenceSchema, NativeHarnessEventSchema, PendingNativeInteractionSchema, NativeHarnessCapabilitiesSchema,
  McpDetectionSchema, ExecutionResultSchema, ApprovalResponseSemanticSchema, AgentHarnessSchema, type AgentConfigurationVersion, type AgentHarness, type NativeSessionReference } from '@foreman-code/contracts'
import type { WorkflowOriginalNativeSource } from '../../interactions/workflowNativeCapture.js'
import type { AcceptedNodePlacement, DispatchIntent } from '@foreman-code/contracts/node-placement'
import { RemoteOperationReceiptSchema, type RemoteOperationReceipt, type RemoteOwnerControl, type RemoteNativeIdentity, type RemoteOwnerReconciliation } from '@foreman-code/contracts/remote-execution'
import type { NativeHarnessSessionManager, NativeSessionStart, NativeTurnInput, NativeHistory } from '../../harnesses/port.js'

export interface RemoteNativeTransport {
  request(method: 'prepare' | 'reattach' | 'start-turn' | 'history' | 'pending' | 'capabilities' | 'inspect-mcp' | 'control' | 'status' | 'reconcile-response' | 'renew-owner' | 'session-controls-read' | 'session-compact' | 'session-compact-reconcile' | 'session-preferences-apply', payload: unknown, signal?: AbortSignal): Promise<unknown>
}
const StatusSchema = z.discriminatedUnion('status', [z.object({ status: z.literal('known'), receipt: RemoteOperationReceiptSchema }).strict(), z.object({ status: z.literal('unknown'), reason: z.literal('journal_absence_requires_reconciliation') }).strict()])
const HistorySchema = z.object({ correlationId: z.string().optional(), nativeTurnId: z.string().optional(), nativeMessageId: z.string().optional(),
  nextCursor: z.string().optional(), firstRetainedSequence: z.number().optional(), nextSequence: z.number().optional(),
  events: z.array(NativeHarnessEventSchema), pendingInteractions: z.array(PendingNativeInteractionSchema), pendingInteraction: PendingNativeInteractionSchema.optional(),
  terminalResult: ExecutionResultSchema.optional(), terminalTurn: z.object({ correlationId: z.string(), providerId: z.string(), result: ExecutionResultSchema }).optional(),
  interactionDeliveries: z.array(z.object({ nativeRequestId: z.string(), state: z.enum(['pending','submitting','submitted','uncertain']), selectedOptionId: z.string().optional() })).optional(),
  responseDeliveries: z.array(z.object({ source: z.enum(['provider_acknowledgement','provider_history']),
    harness: AgentHarnessSchema, providerVersion: z.string(), nativeSessionId: z.string(), nativeRequestId: z.string(),
    nativeRequestType: z.string(), optionId: z.string(), semantic: ApprovalResponseSemanticSchema,
    responseDigest: z.string().regex(/^[a-f0-9]{64}$/).optional() })).optional(),
  canceledRequestIds: z.array(z.string()).optional() }).passthrough()
export interface RemoteNativeManagerOptions {
  intent: DispatchIntent
  placement: AcceptedNodePlacement
  harness: AgentHarness
  configuration: AgentConfigurationVersion
  transport: RemoteNativeTransport
  /** Main-authoritative exact durable command/interaction identity, never generated by the proxy. */
  controlFor(input: { kind: 'stop' | 'respond'; native: RemoteNativeIdentity; nativeRequestId?: string; option?: unknown }): Promise<RemoteOwnerControl>
  observeReceipt(receipt: RemoteOperationReceipt): Promise<void>
  observeOriginalSource?(receipt: RemoteOperationReceipt, source: WorkflowOriginalNativeSource): Promise<void>
}
/** Main-side native port, bound once to the accepted host/attempt. No provider credential crosses it. */
export class RemoteNativeSessionManager implements NativeHarnessSessionManager {
  readonly harness: AgentHarness
  private intent: DispatchIntent
  private session?: NativeSessionReference
  private receipt?: RemoteOperationReceipt
  private streamHistory: {
    value: z.infer<typeof HistorySchema>
    receipt: RemoteOperationReceipt
    observedAt: number
  } | undefined
  private preferences: SessionPreferences | undefined
  private context: ContextSnapshot | null = null
  private appliedPreferences: SessionPreferences | null = null
  private prepareAttempted = false
  private detached = false
  constructor(private readonly options: RemoteNativeManagerOptions) { this.harness = options.harness; this.intent = structuredClone(options.intent) }
  private request(method: Parameters<RemoteNativeTransport['request']>[0], payload: Record<string, unknown>, signal?: AbortSignal) {
    const { operationId: _operationId, ...fields } = payload
    void _operationId
    return this.options.transport.request(method, { method, intent: this.intent, placement: this.options.placement, ...fields }, signal)
  }
  private async status(raw: unknown, intent = this.intent) {
    const status = StatusSchema.parse(raw)
    if (status.status !== 'known') throw new Error('Original worker journal requires reconciliation')
    const receipt = status.receipt
    if (!isDeepStrictEqual(receipt.intent, intent)) throw new Error('Remote receipt binding mismatch')
    if (this.receipt) {
      const original = this.receipt
      if (!isDeepStrictEqual(receipt.connection, original.connection) || receipt.workerIncarnationId !== original.workerIncarnationId
        || receipt.sequence < original.sequence || receipt.sequence === original.sequence && !isDeepStrictEqual(receipt, original)
        || original.native && (!receipt.native || receipt.native.sessionId !== original.native.sessionId
          || receipt.native.processIdentityDigest !== original.native.processIdentityDigest
          || original.native.turnId !== undefined && receipt.native.turnId !== original.native.turnId)
        || original.terminal && !isDeepStrictEqual(receipt.terminal, original.terminal)) throw new Error('Original remote receipt changed')
    }
    await this.options.observeReceipt(receipt)
    this.receipt = receipt
    return receipt
  }
  private assertSession(session: NativeSessionReference) {
    if (!this.session || !isDeepStrictEqual(this.session, session)) throw new Error('Wrong remote native session')
  }
  async renewOwner(transition: RemoteOwnerReconciliation, signal?: AbortSignal) {
    const next = { ...this.intent, owner: transition.nextOwner }
    const raw = await this.options.transport.request('renew-owner', { method: 'renew-owner', intent: next, placement: this.options.placement, transition }, signal)
    const receipt = await this.status(raw, next)
    this.intent = next
    return receipt
  }
  async applySessionPreferences(session: NativeSessionReference, preferences: SessionPreferences, signal?: AbortSignal) {
    this.assertSession(session)
    if (!this.receipt?.native) throw new Error('Original native ownership is unavailable')
    const result = z.object({ status: StatusSchema }).strict().parse(await this.request('session-preferences-apply', {
      native: this.receipt.native, preferences: SessionPreferencesSchema.parse(preferences),
    }, signal))
    await this.status(result.status)
  }
  async configureSessionPreferences(preferences: SessionPreferences) {
    if (this.prepareAttempted) throw new Error('Worker startup preferences require a safe new admission')
    this.preferences = SessionPreferencesSchema.parse(preferences)
  }
  async sessionControlCapabilities(session: NativeSessionReference) {
    this.assertSession(session)
    if (!this.receipt?.native) throw new Error('Original native ownership is unavailable')
    const value = z.object({ capabilities: SessionControlCapabilitiesSchema, context: ContextSnapshotSchema.nullable(),
      preferences: SessionPreferencesSchema.nullable(), status: StatusSchema }).strict().parse(
      await this.request('session-controls-read', { native: this.receipt.native }))
    await this.status(value.status)
    if (value.context && value.context.nativeSessionId !== session.nativeSessionId) throw new Error('Wrong worker context session')
    this.context = value.context
    this.appliedPreferences = value.preferences
    return value.capabilities
  }
  contextSnapshot(session: NativeSessionReference) { this.assertSession(session); return this.context }
  appliedSessionPreferences(session: NativeSessionReference) { this.assertSession(session); return this.appliedPreferences }
  async compactSession(session: NativeSessionReference, input: NativeCompactInput, signal?: AbortSignal) {
    this.assertSession(session)
    if (!this.receipt?.native) throw new Error('Original native ownership is unavailable')
    await input.onDispatch?.()
    const value = z.object({ compaction: CompactionStateSchema, status: StatusSchema }).strict().parse(
      await this.request('session-compact', { native: this.receipt.native,
        requestId: input.requestId, clientCorrelationId: input.clientCorrelationId }, signal))
    await this.status(value.status)
    if (value.compaction.requestId !== input.requestId || value.compaction.nativeSessionId !== session.nativeSessionId) throw new Error('Wrong worker compaction')
    await input.onProgress(value.compaction)
    return value.compaction
  }
  async reconcileCompaction(session: NativeSessionReference, state: import('@graphql/contracts').CompactionState, signal?: AbortSignal) {
    this.assertSession(session)
    if (!this.receipt?.native) throw new Error('Original native ownership is unavailable')
    const value = z.object({ compaction: CompactionStateSchema, status: StatusSchema }).strict().parse(
      await this.request('session-compact-reconcile', { native: this.receipt.native, state }, signal))
    await this.status(value.status)
    return value.compaction
  }
  async capabilities(signal?: AbortSignal) { return NativeHarnessCapabilitiesSchema.parse(await this.request('capabilities', { intent: this.intent, placement: this.options.placement, configuration: this.options.configuration }, signal)) }
  async inspectMcp(signal?: AbortSignal) { return McpDetectionSchema.parse(await this.request('inspect-mcp', { intent: this.intent, placement: this.options.placement, configuration: this.options.configuration }, signal)) }
  async createSession(input: NativeSessionStart, signal?: AbortSignal) {
    if (input.kind === 'operator') throw new Error('Remote proxy owns workflow execution only')
    if (input.environment && (input.environment.agentId !== this.options.configuration.agentId || Object.keys(input.environment.variables).some(key => key !== 'GRAPHQL_MCP_TOKEN'))) throw new Error('Only the exact scoped main application lease may cross the worker carrier')
    const token = input.environment?.variables.GRAPHQL_MCP_TOKEN
    const applicationAccess = token ? { kind: 'scoped-worker-mcp', token, executionId: this.intent.executionId, agentId: this.options.configuration.agentId, operationId: this.intent.operationId, attemptId: this.intent.attemptId, bindingHash: this.intent.bindingHash } : undefined
    if (input.request.executionId !== this.intent.executionId || input.correlationId !== `execution:${this.intent.executionId}`) throw new Error('Remote session execution mismatch')
    this.prepareAttempted = true
    const value = z.object({ session: NativeSessionReferenceSchema, status: StatusSchema }).strict().parse(await this.request('prepare', { intent: this.intent, placement: this.options.placement, request: input.request, ...(this.preferences ? { sessionPreferences: this.preferences } : {}), ...(applicationAccess ? { applicationAccess } : {}) }, signal))
    await this.status(value.status)
    if (this.receipt?.native?.sessionId !== value.session.nativeSessionId || value.session.harness !== this.harness) throw new Error('Original remote session recovery required')
    this.session = structuredClone(value.session)
    await this.options.observeOriginalSource?.(this.receipt!, { type: 'session_created', session: value.session })
    return value.session
  }
  async attachSession(session: NativeSessionReference, input: NativeSessionStart, signal?: AbortSignal) {
    if (input.kind === 'operator' || input.request.executionId !== this.intent.executionId
      || input.correlationId !== `execution:${this.intent.executionId}` || session.harness !== this.harness) throw new Error('Remote session execution mismatch')
    this.prepareAttempted = true
    // Attachment is observation of this exact original session; worker recovery must already have proven/rebound it.
    const value = z.object({ session: NativeSessionReferenceSchema, status: StatusSchema }).strict().parse(await this.request('reattach', { request: input.request, session }, signal))
    const receipt = await this.status(value.status)
    if (!isDeepStrictEqual(value.session, session) || receipt.native?.sessionId !== session.nativeSessionId || session.harness !== this.harness) throw new Error('Original remote session recovery required')
    await this.options.observeOriginalSource?.(receipt, { type: 'session_created', session })
    this.session = structuredClone(session)
    this.detached = false
    return structuredClone(session)
  }
  async *startTurn(session: NativeSessionReference, input: NativeTurnInput, signal?: AbortSignal) {
    this.assertSession(session)
    await this.status(await this.request('start-turn', { operationId: this.intent.operationId, prompt: input.prompt, correlationId: input.clientCorrelationId, ...(input.sessionMode ? { sessionMode: input.sessionMode } : {}) }, signal))
    let sequence = -1, submitted = false
    while (true) {
      signal?.throwIfAborted()
      const value = z.object({ history: HistorySchema, context: ContextSnapshotSchema.nullable().optional(), status: StatusSchema }).strict().parse(await this.request('history', { operationId: this.intent.operationId }, signal))
      const receipt = await this.status(value.status)
      if (value.context !== undefined) this.context = value.context
      if (!submitted && receipt.native?.turnId) { await input.onSubmitted?.(receipt.native.turnId); await input.onSettingsApplied?.(); submitted = true }
      this.streamHistory = { value: value.history, receipt, observedAt: Date.now() }
      try {
        for (const event of value.history.events) {
          if (event.sequence <= sequence) continue
          sequence = event.sequence
          // A caller may refresh history between yields. Use its current original
          // receipt; the Worker still verifies this exact event in that history.
          const currentReceipt = this.receipt!
          if (!submitted && currentReceipt.native?.turnId) {
            await input.onSubmitted?.(currentReceipt.native.turnId)
            submitted = true
          }
          await this.options.observeOriginalSource?.(currentReceipt, {
            type: 'event', event: { ...event, executionId: this.intent.executionId },
          })
          yield event
        }
      } finally {
        this.streamHistory = undefined
      }
      if (value.history.terminalTurn?.correlationId === input.clientCorrelationId || receipt.phase === 'confirmed_terminal') return
      if (receipt.phase === 'uncertain') throw new Error('Original remote execution requires reconciliation')
      await delay(100, undefined, { signal })
    }
  }
  async pending(session: NativeSessionReference, signal?: AbortSignal) { this.assertSession(session); const raw = await this.request('pending', { operationId: this.intent.operationId }, signal); return raw == null ? undefined : PendingNativeInteractionSchema.parse(raw) }
  async respond(session: NativeSessionReference, nativeRequestId: string, option: Parameters<NativeHarnessSessionManager['respond']>[2], signal?: AbortSignal) {
    this.assertSession(session)
    if (!this.receipt?.native) throw new Error('Original remote native ownership missing')
    const command = await this.options.controlFor({ kind: 'respond', native: this.receipt.native, nativeRequestId, option })
    await this.status(await this.request('control', { command, intent: this.intent, placement: this.options.placement }, signal))
  }
  async cancel(session: NativeSessionReference, signal?: AbortSignal, nativeTurnId?: string) {
    this.assertSession(session)
    if (!this.receipt?.native || (nativeTurnId && nativeTurnId !== this.receipt.native.turnId)) throw new Error('Wrong remote cancel turn')
    const command = await this.options.controlFor({ kind: 'stop', native: this.receipt.native })
    await this.status(await this.request('control', { command, intent: this.intent, placement: this.options.placement }, signal))
    await this.history(session, signal)
    // Requested cancellation is not confirmed physical closure.
    return this.receipt?.phase === 'confirmed_terminal' && this.receipt.terminal?.kind === 'cancelled'
  }
  async history(session: NativeSessionReference, signal?: AbortSignal): Promise<NativeHistory> {
    this.assertSession(session)
    signal?.throwIfAborted()
    const streamed = this.streamHistory
    if (streamed && Date.now() - streamed.observedAt < 30_000 && isDeepStrictEqual(streamed.receipt, this.receipt)) {
      const history = this.projectHistory(streamed.value)
      await this.options.observeOriginalSource?.(streamed.receipt, { type: 'history', history })
      return history
    }
    const value = z.object({ history: HistorySchema, context: ContextSnapshotSchema.nullable().optional(), status: StatusSchema }).strict().parse(await this.request('history', { operationId: this.intent.operationId }, signal))
    await this.status(value.status)
    if (value.context !== undefined) this.context = value.context
    if (streamed) this.streamHistory = { value: value.history, receipt: this.receipt!, observedAt: Date.now() }
    const history = this.projectHistory(value.history)
    await this.options.observeOriginalSource?.(this.receipt!, { type: 'history', history })
    return history
  }
  async observeBoundary(session: NativeSessionReference, signal?: AbortSignal): Promise<void> {
    this.assertSession(session)
    const receipt = await this.status(await this.request('status', {}, signal))
    await this.options.observeOriginalSource?.(receipt, { type: 'boundary' })
  }
  private projectHistory(history: z.infer<typeof HistorySchema>): NativeHistory {
    return { events: history.events, pendingInteractions: history.pendingInteractions,
      ...(history.correlationId === undefined ? {} : { correlationId: history.correlationId }),
      ...(history.nativeTurnId === undefined ? {} : { nativeTurnId: history.nativeTurnId }),
      ...(history.nativeMessageId === undefined ? {} : { nativeMessageId: history.nativeMessageId }),
      ...(history.nextCursor === undefined ? {} : { nextCursor: history.nextCursor }),
      ...(history.firstRetainedSequence === undefined ? {} : { firstRetainedSequence: history.firstRetainedSequence }),
      ...(history.nextSequence === undefined ? {} : { nextSequence: history.nextSequence }),
      ...(history.pendingInteraction === undefined ? {} : { pendingInteraction: history.pendingInteraction }),
      ...(history.terminalResult === undefined ? {} : { terminalResult: history.terminalResult }),
      ...(history.terminalTurn === undefined ? {} : { terminalTurn: history.terminalTurn }),
      ...(history.responseDeliveries === undefined ? {} : { responseDeliveries: history.responseDeliveries }),
      ...(history.interactionDeliveries === undefined ? {} : { interactionDeliveries: history.interactionDeliveries.map(value => ({ nativeRequestId: value.nativeRequestId, state: value.state, ...(value.selectedOptionId === undefined ? {} : { selectedOptionId: value.selectedOptionId }) })) }),
      ...(history.canceledRequestIds === undefined ? {} : { canceledRequestIds: history.canceledRequestIds }) }
  }
  async reconcile(session: NativeSessionReference, correlationId: string, signal?: AbortSignal) {
    if (correlationId !== `execution:${this.intent.executionId}`) throw new Error('Wrong remote reconciliation correlation')
    return this.history(session, signal)
  }
  async reconcileResponse(session: NativeSessionReference, response: Parameters<NonNullable<NativeHarnessSessionManager['reconcileResponse']>>[1], signal?: AbortSignal) {
    this.assertSession(session)
    const value = z.object({ history: HistorySchema, context: ContextSnapshotSchema.nullable().optional(), status: StatusSchema }).strict().parse(await this.request('reconcile-response', { response }, signal))
    await this.status(value.status)
    const history = this.projectHistory(value.history)
    await this.options.observeOriginalSource?.(this.receipt!, { type: 'history', history })
    return history
  }
  async close(session: NativeSessionReference) { this.assertSession(session); if (this.receipt?.phase !== 'confirmed_terminal') await this.cancel(session); if (this.receipt?.phase !== 'confirmed_terminal') throw new Error('Original remote native closure is unconfirmed') }
  async dispose() {
    if (!this.prepareAttempted) return
    if (!this.detached && this.receipt?.phase !== 'confirmed_terminal') throw new Error('Original remote native disposal is unconfirmed')
  }
  async closeForRestart(session: NativeSessionReference) { this.assertSession(session); await this.history(session); this.detached = true }
}
